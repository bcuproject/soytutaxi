// Generates supabase/seed.sql from the shared demo fixtures. Run: npm run gen:seed
import { writeFileSync } from "node:fs";
import {
  DEMO_AIRPORTS, DEMO_BOOKINGS, DEMO_DRIVERS, DEMO_FARE_RULES, DEMO_OPERATOR_ID, DEMO_POLICY, DEMO_VEHICLE_CLASSES,
  DEMO_VEHICLES, DEMO_ZONES,
} from "../supabase/functions/_shared/domain/fixtures.ts";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const OP = q(DEMO_OPERATOR_ID);
const out: string[] = [];

out.push(`-- GENERATED by scripts/gen-seed.ts from supabase/functions/_shared/domain/fixtures.ts — do not edit.
-- DEMO DATA: clearly labelled example values. Replace fares and policies before production.
begin;
insert into public.operators (id, slug, name, timezone, demo_mode)
values (${OP}, 'soytutaxi', 'SoyTuTaxi (DEMO)', 'America/Argentina/Buenos_Aires', true)
on conflict (id) do nothing;
`);

for (const v of DEMO_VEHICLE_CLASSES) {
  out.push(`insert into public.vehicle_classes (operator_id, code, label_es, label_en, max_passengers, max_large_bags, max_carry_on, max_bag_units, sort_order, active)
values (${OP}, ${q(v.code)}, ${q(v.labelEs)}, ${q(v.labelEn)}, ${v.maxPassengers}, ${v.maxLargeBags}, ${v.maxCarryOn}, ${q(v.maxBagUnits)}, ${v.sortOrder}, ${v.active}) on conflict do nothing;`);
}
for (const a of DEMO_AIRPORTS) {
  out.push(`insert into public.airports (id, operator_id, iata, name, meeting_point_es, meeting_point_en, lat, lng)
values (${q(a.id)}, ${OP}, ${q(a.iata)}, ${q(a.name)}, ${q(a.meetingPointEs)}, ${q(a.meetingPointEn)}, ${a.lat}, ${a.lng}) on conflict do nothing;`);
}
for (const z of DEMO_ZONES) {
  out.push(`insert into public.zones (id, operator_id, code, name, polygon) values (${q(z.id)}, ${OP}, ${q(z.code)}, ${q(z.name)}, ${j(z.polygon)}) on conflict do nothing;`);
}
out.push(`insert into public.policies (id, operator_id, version, label, is_demo, config, effective_from)
values (${q(DEMO_POLICY.id)}, ${OP}, ${DEMO_POLICY.version}, ${q(DEMO_POLICY.label)}, true, ${j(DEMO_POLICY.config)}, '2026-01-01T00:00:00Z') on conflict do nothing;`);
out.push(`insert into public.fare_rules (id, operator_id, direction, airport_id, zone_id, vehicle_class, rank, amount_minor, taxes_minor, currency, est_duration_min, effective, is_demo, version) values
${DEMO_FARE_RULES.map((f) => `(${q(f.id)}, ${OP}, ${q(f.direction)}, ${q(f.airportId)}, ${q(f.zoneId)}, ${q(f.vehicleClass)}, ${f.rank}, ${f.amountMinor}, ${f.taxesMinor}, ${q(f.currency)}, ${f.estDurationMin}, daterange(${q(f.effectiveFrom)}, ${q(f.effectiveTo)}, '[)'), true, ${f.version})`).join(",\n")}
on conflict do nothing;`);
for (const v of DEMO_VEHICLES) {
  out.push(`insert into public.vehicles (id, operator_id, vehicle_class, plate, description) values (${q(v.id)}, ${OP}, ${q(v.vehicleClass)}, ${q(v.plate)}, ${q(v.description)}) on conflict do nothing;`);
}
for (const d of DEMO_DRIVERS) {
  out.push(`insert into public.drivers (id, operator_id, full_name, whatsapp_e164, whatsapp_verified_at, approval_status) values (${q(d.id)}, ${OP}, ${q(d.fullName)}, ${q(d.whatsappE164)}, ${d.approvalStatus === "approved" ? "now()" : "null"}, ${q(d.approvalStatus)}) on conflict do nothing;`);
  if (d.vehicleId) {
    out.push(`insert into public.driver_vehicle_allocations (operator_id, driver_id, vehicle_id, period) select ${OP}, ${q(d.id)}, ${q(d.vehicleId)}, tstzrange('2026-01-01T00:00:00Z', null, '[)') where not exists (select 1 from public.driver_vehicle_allocations where driver_id = ${q(d.id)});`);
    // Demo shift: every day 05:00–23:00 local.
    out.push(`insert into public.driver_availability (operator_id, driver_id, kind, weekday, start_local, end_local, effective) select ${OP}, ${q(d.id)}, 'recurring_shift', wd, '05:00', '23:00', daterange('2026-01-01', null, '[)') from generate_series(0,6) wd where not exists (select 1 from public.driver_availability where driver_id = ${q(d.id)});`);
  }
}

// Demo bookings relative to today's date in Buenos Aires: one data table + one loop.
const demoRows = DEMO_BOOKINGS.map((d, i) => {
  const driver = d.driverIndex !== undefined && d.state !== "cancelled" ? DEMO_DRIVERS[d.driverIndex] : null;
  return `(${[q(d.reference), d.dayOffset, q(d.direction), q(d.airport), q(d.zoneCode), q(d.placeText), q(d.time), q(d.flight),
    d.passengers, d.largeBags, d.carryOn, q(d.vehicleClass), q(d.paymentMode), q(d.passenger.name), q(d.passenger.phone),
    q(d.passenger.locale), q(d.state), driver ? q(driver.id) : "null", driver ? q(driver.vehicleId) : "null", q(d.notes ?? null), i].join(", ")})`;
}).join(",\n    ");

out.push(`
do $seed$
declare
  tz constant text := 'America/Argentina/Buenos_Aires';
  v_today date := (now() at time zone tz)::date;
  d record; v_quote uuid; v_pass uuid; v_booking uuid; v_pickup timestamptz; v_arrival timestamptz; v_buffer int;
  v_rule public.fare_rules%rowtype; v_airport public.airports%rowtype; v_zone public.zones%rowtype;
  v_city jsonb; v_ap jsonb; v_flight jsonb; v_journey jsonb;
  v_pol jsonb := (select config from public.policies where id = ${q(DEMO_POLICY.id)});
begin
  if exists (select 1 from public.bookings where reference like 'STT-DEM%') then return; end if;
  for d in select * from (values
    ${demoRows}
  ) as t(ref, day_offset, direction, airport, zone_code, place_text, at_time, flight, pax, large_bags, carry_on,
         vehicle_class, payment_mode, p_name, p_phone, p_locale, state, driver_id, vehicle_id, notes, idx)
  loop
    select * into v_airport from public.airports where operator_id = ${OP} and iata = d.airport;
    select * into v_zone from public.zones where operator_id = ${OP} and code = d.zone_code;
    select * into v_rule from public.fare_rules where operator_id = ${OP} and direction = d.direction::public.journey_direction
      and airport_id = v_airport.id and zone_id = v_zone.id and vehicle_class = d.vehicle_class and active;
    v_buffer := (v_pol -> 'arrival_buffer_minutes' ->> d.airport)::int;
    if d.direction = 'from_airport' then
      v_arrival := ((v_today + d.day_offset) + d.at_time::time) at time zone tz;
      v_pickup := v_arrival + make_interval(mins => v_buffer);
      v_flight := jsonb_build_object('designator', d.flight, 'localArrivalDate', (v_today + d.day_offset)::text,
        'scheduledArrivalAt', v_arrival, 'scheduledArrivalLocal', d.at_time, 'bufferMinutes', v_buffer);
    else
      v_arrival := null; v_flight := null;
      v_pickup := ((v_today + d.day_offset) + d.at_time::time) at time zone tz;
    end if;
    v_city := jsonb_build_object('label', d.place_text, 'originalText', d.place_text, 'lat', null, 'lng', null,
      'verified', false, 'zoneCode', d.zone_code, 'kind', 'address');
    v_ap := jsonb_build_object('label', v_airport.name || ' (' || v_airport.iata || ')', 'originalText', v_airport.iata,
      'lat', v_airport.lat, 'lng', v_airport.lng, 'verified', true, 'zoneCode', null, 'kind', 'airport');
    v_journey := jsonb_build_object('direction', d.direction, 'airportIata', v_airport.iata, 'airportId', v_airport.id,
      'zoneId', v_zone.id, 'zoneCode', v_zone.code,
      'pickup', case when d.direction = 'from_airport' then v_ap else v_city end,
      'dropoff', case when d.direction = 'from_airport' then v_city else v_ap end,
      'pickupAt', v_pickup, 'flight', v_flight, 'passengers', d.pax, 'largeBags', d.large_bags, 'carryOn', d.carry_on, 'locale', d.p_locale);
    insert into public.quotes (operator_id, session_hash, source, kind, direction, airport_id, zone_id, vehicle_class, passengers,
      large_bags, carry_on, pickup_at, journey, fare, amount_minor, currency, fare_rule_id, fare_rule_version, policy_id, expires_at, created_at)
    values (${OP}, 'seed', 'web', 'priced', d.direction::public.journey_direction, v_airport.id, v_zone.id, d.vehicle_class, d.pax,
      d.large_bags, d.carry_on, v_pickup, v_journey,
      jsonb_build_object('baseMinor', v_rule.amount_minor, 'taxesMinor', v_rule.taxes_minor, 'totalMinor', v_rule.amount_minor + v_rule.taxes_minor,
        'currency', v_rule.currency, 'fareRuleId', v_rule.id, 'fareRuleVersion', v_rule.version, 'estDurationMin', v_rule.est_duration_min, 'isDemo', true),
      v_rule.amount_minor + v_rule.taxes_minor, v_rule.currency, v_rule.id, v_rule.version, ${q(DEMO_POLICY.id)},
      now() - interval '1 day', now() - make_interval(hours => d.idx + 2))
    returning id into v_quote;
    insert into public.passengers (operator_id, full_name, phone_e164, locale) values (${OP}, d.p_name, d.p_phone, d.p_locale)
    returning id into v_pass;
    insert into public.bookings (operator_id, reference, source, quote_id, passenger_id, direction, airport_id, zone_id, pickup_place,
      dropoff_place, passengers, large_bags, carry_on, vehicle_class, flight_designator, flight_local_arrival_date,
      flight_scheduled_arrival_at, agreed_pickup_at, est_duration_min, state, payment_mode, collection_state, amount_minor, currency,
      policy_id, locale, notes, status_token_hash, status_token_expires_at, idempotency_key, request_hash, cancelled_reason, created_at)
    values (${OP}, d.ref, 'web', v_quote, v_pass, d.direction::public.journey_direction, v_airport.id, v_zone.id,
      v_journey -> 'pickup', v_journey -> 'dropoff', d.pax, d.large_bags, d.carry_on, d.vehicle_class,
      d.flight, case when d.flight is not null then v_today + d.day_offset end, v_arrival, v_pickup, v_rule.est_duration_min,
      d.state::public.booking_state, d.payment_mode::public.payment_mode,
      (case when d.payment_mode <> 'prepaid' then 'pending_collection' when d.state = 'confirmed' then 'collected' else 'awaiting_payment' end)::public.collection_state,
      v_rule.amount_minor + v_rule.taxes_minor, v_rule.currency, ${q(DEMO_POLICY.id)}, d.p_locale, d.notes,
      'seed-no-public-access', now() + interval '30 days', 'demo-' || d.ref, 'seed',
      case when d.state = 'cancelled' then 'Cancelado por el pasajero (demo)' end, now() - make_interval(hours => d.idx + 2))
    returning id into v_booking;
    update public.quotes set consumed_booking_id = v_booking, consumed_at = now() where id = v_quote;
    insert into public.trip_events (operator_id, booking_id, kind, to_value, source, payload)
    values (${OP}, v_booking, 'booking.created', 'needs_driver', 'web', '{"seed":true}');
    if d.driver_id is not null then
      insert into public.assignments (operator_id, booking_id, driver_id, vehicle_id, state, hold_expires_at, occupied)
      values (${OP}, v_booking, d.driver_id::uuid, d.vehicle_id::uuid,
        (case when d.state = 'held' then 'reserving' else 'confirmed' end)::public.assignment_state,
        case when d.state = 'held' then now() + interval '12 minutes' end,
        tstzrange(v_pickup, v_pickup + make_interval(mins => v_rule.est_duration_min + (v_pol ->> 'turnaround_minutes')::int), '[)'));
      insert into public.trip_events (operator_id, booking_id, kind, from_value, to_value, payload)
      values (${OP}, v_booking, 'booking.state_changed', 'needs_driver', d.state,
        jsonb_build_object('driver', (select full_name from public.drivers where id = d.driver_id::uuid)));
    end if;
  end loop;
end $seed$;
commit;
`);

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql written: ${DEMO_FARE_RULES.length} fare rules, ${DEMO_BOOKINGS.length} demo bookings`);
