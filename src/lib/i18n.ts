const dicts: Record<Locale, Dict> = { "es-AR": es, en };

export type T = (key: Key | string, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): T {
  return (key, vars) => {
    const d = dicts[locale] as Record<string, string>;
    let s = d[key] ?? (es as Record<string, string>)[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export const LocaleContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: T }>({
  locale: "es-AR", setLocale: () => {}, t: makeT("es-AR"),
});
export const useI18n = () => useContext(LocaleContext);
